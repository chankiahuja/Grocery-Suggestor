CREATE TABLE inventory_items (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name TEXT NOT NULL, category TEXT NOT NULL, quantity DOUBLE PRECISION NOT NULL CHECK (quantity >= 0),
 unit TEXT NOT NULL, min_threshold DOUBLE PRECISION NOT NULL CHECK (min_threshold >= 0),
 expires_at DATE, notes TEXT,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE shopping_lists (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE shopping_list_items (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 shopping_list_id BIGINT NOT NULL REFERENCES shopping_lists(id) ON DELETE CASCADE,
 inventory_item_id BIGINT REFERENCES inventory_items(id) ON DELETE SET NULL,
 name TEXT NOT NULL, category TEXT NOT NULL, quantity DOUBLE PRECISION NOT NULL CHECK (quantity >= 0),
 unit TEXT NOT NULL, purchased BOOLEAN NOT NULL DEFAULT FALSE, notes TEXT,
 restocked BOOLEAN NOT NULL DEFAULT FALSE
);
