CREATE TABLE inventory_adjustments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 inventory_item_id BIGINT NOT NULL REFERENCES inventory_items(id) ON DELETE CASCADE,
 idempotency_key TEXT NOT NULL,
 operation TEXT NOT NULL CHECK (operation IN ('consume', 'restock')),
 amount DOUBLE PRECISION NOT NULL CHECK (amount > 0),
 quantity_before DOUBLE PRECISION NOT NULL CHECK (quantity_before >= 0),
 quantity_after DOUBLE PRECISION NOT NULL CHECK (quantity_after >= 0),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT inventory_adjustments_idempotency UNIQUE (inventory_item_id, idempotency_key)
);

CREATE INDEX inventory_adjustments_item_created_idx
 ON inventory_adjustments (inventory_item_id, created_at);
